import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';

async function main() {
 const base=process.env.QUIETOPS_URL || 'http://127.0.0.1:3002';
 const root=path.resolve('demo/assets/tabpfn');
 await mkdir(path.join(root,'raw'),{recursive:true});
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const context=await browser.newContext({viewport:{width:1600,height:1000},reducedMotion:'reduce',recordVideo:{dir:path.join(root,'raw'),size:{width:1600,height:1000}}});
 const page=await context.newPage(), video=page.video();
 const errors:string[]=[], scenes:{at:number;text:string}[]=[];
 page.on('pageerror',e=>errors.push(e.message));
 const started=Date.now();
 const scene=async(text:string,shot?:string)=>{scenes.push({at:(Date.now()-started)/1000,text});console.log(text);await page.waitForTimeout(2400);if(shot)await page.screenshot({path:path.join(root,shot),fullPage:false});};
 let state:any;
 try {
  await page.goto(base);await expect(page.getByText('Opening your local workspace…',{exact:true})).toBeHidden();
  const demo=page.getByRole('button',{name:'Explore a demo shop'});
  if(!await demo.isVisible())throw new Error('Recording requires an empty isolated QUIETOPS_DATA directory.');
  await demo.click();await expect(page.getByText('Fictional shop demo',{exact:true})).toBeVisible();
  await scene('The original fictional shop: deterministic checks and source-linked findings.','01-deterministic.png');
  await page.getByRole('button',{name:'Looking Ahead',exact:true}).click();
  await scene('One stock snapshot cannot train a historical predictor. Add explicitly synthetic history.');
  await page.getByRole('button',{name:'Load predictive example',exact:true}).click();
  await expect(page.getByRole('button',{name:'Run TabPFN prediction',exact:true})).toBeEnabled();
  scenes.push({at:(Date.now()-started)/1000,text:'Run genuine local TabPFN-3.5 inference. No fallback model supplies these probabilities.'});
  await page.getByRole('button',{name:'Run TabPFN prediction',exact:true}).click();
  await expect(page.getByRole('heading',{name:'A closer look at the shelf',exact:true})).toBeVisible({timeout:180000});
  await page.getByRole('heading',{name:'A closer look at the shelf',exact:true}).evaluate(e=>e.scrollIntoView({block:'start'}));
  await scene('SKU-007: both simple rules show cover; TabPFN estimates uncertain future demand risk.','02-looking-ahead.png');
  const row=page.getByRole('row').filter({hasText:'SKU-007'});
  await expect(row).toContainText('Beyond cover rule');
  await row.getByRole('button',{name:'Inspect prediction'}).click();
  await scene('Follow the stock snapshot and both sales files. The probability comes from TabPFN.','03-evidence.png');
  await page.getByText('Assumptions & limits',{exact:true}).click();
  await scene('Assume no incoming receipt. This constructed example was selected after model exploration.');
  const explain=page.getByRole('button',{name:'Explain with local AI',exact:true});
  await explain.scrollIntoViewIfNeeded();await expect(explain).toBeEnabled({timeout:30000});
  scenes.push({at:(Date.now()-started)/1000,text:'Ministral runs locally to explain supplied facts and draft a review step.'});
  const explained=page.waitForResponse(r=>r.url().endsWith('/explain')&&r.request().method()==='POST',{timeout:210000});
  await explain.click();
  const explanationResponse=await explained;
  if(!explanationResponse.ok())throw new Error(await explanationResponse.text());
  await expect(page.getByText('Suggested next step',{exact:true})).toBeVisible({timeout:210000});
  await page.locator('.ai-section').scrollIntoViewIfNeeded();
  await scene('Grounded local explanation: model uncertainty and human review remain visible.','04-ministral.png');
  await page.getByRole('button',{name:'Create action draft',exact:true}).click();
  await page.getByRole('button',{name:'Review & decide',exact:true}).first().click();
  const body=page.getByLabel('Draft text',{exact:true});
  await body.fill((await body.inputValue())+'\n\nReviewer edit (fictional demo): Please confirm the delivery plan and check the recurring demand pattern before any purchase decision.');
  await scene('Edit the supplier-review draft. Approval only makes it available for manual export.','05-editable-draft.png');
  await page.getByRole('button',{name:'Approve for export',exact:true}).click();
  await scene('Approved draft. Nothing has been sent, ordered, or changed in the shop records.','06-approved.png');
  const download=page.waitForEvent('download');await page.getByRole('link',{name:'Export approved drafts'}).click();
  await (await download).saveAs(path.join(root,'approved-supplier-review.md'));
  await page.getByRole('button',{name:'Looking Ahead',exact:true}).click();
  await page.getByRole('heading',{name:'Held-out historical comparison',exact:true}).scrollIntoViewIfNeeded();
  await scene('Compare actual later-date precision, recall and F1 against both baselines. Synthetic data only.','07-comparison.png');
  state=await (await context.request.get(base+'/api/state')).json();
  expect(state.prediction_run.model.inference_ran).toBe(true);
  const risk=state.predictions.find((p:any)=>p.subject==='SKU-007');
  expect(risk.overlooked_by_rule).toBe(true);expect(risk.ai.model).toContain('ministral');
  expect(state.actions.some((a:any)=>a.status==='approved'&&a.scope==='prediction')).toBe(true);
  expect(errors).toEqual([]);
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:path.join(root,'08-mobile.png'),fullPage:true});
 } finally {await context.close();await browser.close();}
 const end=(Date.now()-started)/1000;
 const stamp=(s:number)=>{const ms=Math.round(s*1000);return `${Math.floor(ms/3600000).toString().padStart(2,'0')}:${Math.floor(ms/60000)%60<10?'0':''}${Math.floor(ms/60000)%60}:${Math.floor(ms/1000)%60<10?'0':''}${Math.floor(ms/1000)%60},${(ms%1000).toString().padStart(3,'0')}`;};
 await writeFile(path.join(root,'captions.srt'),scenes.map((s,i)=>`${i+1}\n${stamp(s.at)} --> ${stamp(scenes[i+1]?.at ?? end)}\n${s.text}\n`).join('\n'));
 const converted=spawnSync('ffmpeg',['-y','-i',await video!.path(),'-vf',"subtitles=demo/assets/tabpfn/captions.srt:force_style='FontName=Arial,FontSize=16,Outline=1,MarginV=18'",'-c:v','libx264','-preset','fast','-crf','22','-pix_fmt','yuv420p','-movflags','+faststart',path.join(root,'looking-ahead-demo.mp4')],{encoding:'utf8'});
 if(converted.status!==0)throw new Error(converted.stderr);
 const report={recorded_at:new Date().toISOString(),duration_seconds:end,synthetic:true,constructed_live_example_selected_after_exploration:true,model:state.prediction_run.model,comparison:state.prediction_run.comparison,local_explanation:state.predictions.find((p:any)=>p.subject==='SKU-007').ai,browser_errors:errors,scenes};
 await writeFile(path.join(root,'recording-report.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify({complete:true,duration_seconds:end,output:'demo/assets/tabpfn/looking-ahead-demo.mp4'}));
}
main().catch(e=>{console.error(e);process.exitCode=1;});
